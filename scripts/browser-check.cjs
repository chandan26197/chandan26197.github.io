const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('fs');
const path = require('path');
const os = require('os');
const root = path.resolve(__dirname, '..');
const profile = JSON.parse(fs.readFileSync(path.join(root, 'inputs/profile.json'), 'utf8'));
const total = profile.work.length;
const developerCount = profile.work.filter(item => item.category === 'developer-tools').length;
const systemsCount = profile.work.filter(item => item.category === 'systems').length;
const output = process.env.PREVIEW_DIR || path.join(os.tmpdir(), 'chandan-portfolio-preview');
fs.mkdirSync(output, {recursive:true});
(async () => {
  const browser = await chromium.launch({headless:true});
  const page = await browser.newPage({viewport:{width:1440,height:1000},colorScheme:'light'});
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(process.env.PORTFOLIO_URL || require('url').pathToFileURL(path.join(root, '_site/index.html')).href);
  if(await page.locator('h1').count()!==1) throw Error('Expected one heading');
  if(await page.locator('.work-item:visible').count()!==total) throw Error('Unexpected number of work entries');
  await page.getByRole('button',{name:'AI & developer tools'}).click();
  if(await page.locator('.work-item:visible').count()!==developerCount) throw Error('Developer tools filter failed');
  await page.getByRole('button',{name:'Systems & security'}).click();
  if(await page.locator('.work-item:visible').count()!==systemsCount) throw Error('Systems filter failed');
  await page.getByRole('button',{name:'All work'}).click();
  if (profile.photo.path) {
    const portrait = page.locator('.portrait');
    await portrait.evaluate(image => image.decode());
    if (!await portrait.evaluate(image => image.naturalWidth > 0 && image.naturalHeight > 0)) throw Error('Profile photo failed to load');
    if (!await portrait.getAttribute('alt')) throw Error('Profile photo needs alt text');
    if (await page.locator('.monogram:visible').count()) throw Error('Monogram should be hidden when a profile photo is shown');
  }
  await page.screenshot({path:path.join(output, 'desktop.png'),fullPage:true});
  await page.getByRole('button',{name:'Switch to dark color theme'}).click();
  await page.reload();
  if(await page.locator('html').getAttribute('data-theme')!=='dark') throw Error('Theme persistence failed');
  await page.getByRole('button',{name:'Switch to light color theme'}).click();
  await page.setViewportSize({width:390,height:844});
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)) throw Error('Mobile horizontal overflow');
  await page.screenshot({path:path.join(output, 'mobile.png'),fullPage:true});
  const nojs = await browser.newContext({javaScriptEnabled:false,viewport:{width:390,height:844}});
  const staticPage = await nojs.newPage();
  await staticPage.goto(process.env.PORTFOLIO_URL || require('url').pathToFileURL(path.join(root, '_site/index.html')).href);
  if(await staticPage.locator('.work-item:visible').count()!==total) throw Error('No-JS content unavailable');
  await staticPage.keyboard.press('Tab');
  if(await staticPage.locator(':focus').textContent()!=='Skip to content') throw Error('Skip link failed');
  if(errors.length) throw Error(errors.join('\n'));
  console.log('Passed: desktop/mobile rendering, work filters, persistent theme, no-JavaScript content, keyboard skip link, and no browser errors.');
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1)});
